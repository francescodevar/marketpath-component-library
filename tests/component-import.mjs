import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { unzipSync, strFromU8 } from 'fflate';
import { createComponentImport, createThemeImportZip, createThemeMarketpathImport } from '../src/lib/marketpath-export.js';
import overlay from '../src/catalog/services/services-03/component.js';
import stackCards from '../src/catalog/services/services-02/component.js';
import detail from '../src/catalog/inside-services/services-individual-01/component.js';
import services from '../src/datastores/services/datastore.js';
import faqs from '../src/datastores/faqs/datastore.js';
import gallery from '../src/catalog/gallery/gallery-01/component.js';
import header from '../src/catalog/header/header-02/component.js';
import footer from '../src/catalog/footer/footer-01/component.js';
import settings from '../src/datastores/page-settings/datastore.js';

const options = { component: overlay, datastores: [services, faqs], siteDomain: 'https://example.marketpath.site', pagePath: '/services-cards-with-overlay-example', includePageExample: true };
const result = createComponentImport(options);
const archive = unzipSync(createThemeImportZip({ packageData: result, placeholderImage: readFileSync(new URL('../public/placeholder.jpg', import.meta.url)) }));
const packaged = JSON.parse(strFromU8(archive['ALL.json']));
const article = packaged.Article[0];
assert.equal(article.URL, '//example.marketpath.site/services-cards-with-overlay-example');
assert(packaged.Template.some((template) => template.Name === article.TemplateGUID && template.Type === 'page'));
assert.deepEqual(article.services_items, packaged.DatastoreItem.map((item) => item.Name));
assert(article.services_title);
assert(archive[packaged.Image[0].FileGUID]?.length > 0);
assert(packaged.DatastoreItem.every((item) => item.services_image === packaged.Image[0].Name));
assert(!packaged.Datastore.some((datastore) => datastore.Name === 'FAQs'));
assert.deepEqual(packaged.Template.map((template) => template.Name), ['/partials/services/services-03.liquid', '/pages/_services-03-example.liquid']);
assert(packaged.DatastoreItem.every((item) => !item.URL && !item.TemplateGUID));
assert(packaged.Datastore.every((datastore) => !datastore.DefaultTemplateGUID));
const stackPackage = createComponentImport({ ...options, component: stackCards });
assert.deepEqual(stackPackage.Template.map((template) => template.Name), ['/partials/services/services-02.liquid', '/pages/_services-02-example.liquid']);
assert.equal(stackPackage.DatastoreItem.length, 3);
assert.equal(stackPackage.Article.length, 1);
for (const siteDomain of ['', 'example.com/unexpected-path', 'https://user:password@example.com']) {
  assert.throws(() => createComponentImport({ ...options, siteDomain }), /target site domain/);
}
assert.throws(() => createComponentImport({ ...options, pagePath: '//another-site/page' }), /page route/);
const withoutExamples = createComponentImport({ ...options, siteDomain: '', includeExamples: false, includePageExample: false });
assert.equal(withoutExamples.Article, undefined);
assert.equal(withoutExamples.Image, undefined);

const entityPackage = createComponentImport({ ...options, component: detail, pagePath: '/services/' });
assert(entityPackage.Datastore.some((datastore) => datastore.Name === 'FAQs'));
const entityServices = entityPackage.DatastoreItem.filter((item) => item.DatastoreGUID === 'Services');
assert.deepEqual(entityServices.map((item) => item.Name), ['Example Service 1', 'Example Service 2', 'Example Service 3']);
assert.deepEqual(entityServices.map((item) => item.Title), ['Home repairs', 'Windows & doors', 'Outdoor living']);
assert(entityServices.every((item) => item.TemplateGUID === '/pages/_individual_service.liquid' && item.services_individual_01_faqs.length));
assert(entityServices.every((item) => item.URL.startsWith('//example.marketpath.site/services/')));
assert.equal(entityPackage.Article, undefined);
const customEntityPackage = createComponentImport({ ...options, component: detail, pagePath: '/example-services' });
assert.equal(customEntityPackage.Datastore.find((datastore) => datastore.Name === 'Services').DefaultRootPath, '/example-services/');
assert(customEntityPackage.DatastoreItem.filter((item) => item.DatastoreGUID === 'Services').every((item) => item.URL.startsWith('//example.marketpath.site/example-services/')));

const dataOnly = createComponentImport({ component: overlay, datastores: [services, faqs] });
assert.equal(dataOnly.Article, undefined);
assert.equal(dataOnly.DatastoreItem.length, 3);
assert(dataOnly.DatastoreItem.every((item) => item.services_summary && item.services_content && item.services_image === 'placeholder.jpg'));
assert(dataOnly.DatastoreItem.every((item) => !item.URL && !item.TemplateGUID));
assert(dataOnly.Datastore.every((datastore) => !datastore.DefaultTemplateGUID && !datastore.DefaultRootPath));
assert(!dataOnly.Template.some((template) => template.Name === '/pages/_example_service_detail.liquid'));
assert(!dataOnly.Datastore.some((datastore) => datastore.Name === 'FAQs'));
const detailDataOnly = createComponentImport({ component: detail, datastores: [services, faqs] });
assert.equal(detailDataOnly.Article, undefined);
assert(detailDataOnly.DatastoreItem.some((item) => item.DatastoreGUID === 'FAQs'));
assert(detailDataOnly.DatastoreItem.every((item) => !item.URL && !item.TemplateGUID));
assert(detailDataOnly.DatastoreItem.filter((item) => item.DatastoreGUID === 'Services').every((item) => item.services_individual_01_faqs.length));
assert.throws(() => createComponentImport({ ...options, includeExamples: false }), /Include example content/);
const galleryPackage = createComponentImport({ ...options, component: gallery });
assert.equal(gallery.template.match(/tag\.name\.value \| url_encode \| escape/g)?.length, 3, 'Buttons, mobile options, and image tags must use the same text key');
assert(!gallery.template.includes('tag.guid'), 'Marketpath GUID objects cannot be passed to string filters');
assert.deepEqual(galleryPackage.Article[0].gallery_filters, ['Interior', 'Exterior']);
assert.deepEqual(galleryPackage.Tag, [{ Name: 'Interior', Title: 'Interior' }, { Name: 'Exterior', Title: 'Exterior' }]);
assert.deepEqual(galleryPackage.Image[0].Tags, galleryPackage.Article[0].gallery_filters);
assert(galleryPackage.ImagePreset.some((preset) => preset.Code === 'webp' && preset.QueryString === 'format=webp'));
const galleryTheme = createThemeMarketpathImport({ pages: [{ key: 'gallery', label: 'Gallery', blocks: [{ id: gallery.id }] }], headerId: header.id, footerId: footer.id, components: [header, footer, gallery], datastores: [settings], siteDomain: 'example.com' });
assert.deepEqual(galleryTheme.Article[0].gallery_filters, ['Interior', 'Exterior']);
assert(galleryTheme.Tag.every((tag) => tag.Name && tag.Title === tag.Name));
assert(galleryTheme.ImagePreset.some((preset) => preset.Code === 'webp'));
console.log('PASS: Article, template, domain routes, custom values, image ZIP entries, and component-scoped entity examples.');
